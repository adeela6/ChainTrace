"""Block building and append rules for ChainTrace (FR-4).

A block is a plain dict with the fields from the team doc:

    index, block_id, timestamp, case_id, evidence_id, event_type, actor_id,
    key_fingerprint, payload, prev_hash, signature, block_hash

- "Signing fields" are every field except signature and block_hash.
- signature  = Ed25519 over canonical JSON of the signing fields (base64).
- block_hash = SHA-256 of canonical JSON of (signing fields + signature).

The engine never touches the database. The backend gives it the last block,
gets a new block back, checks it, and stores it.
"""

import re
import uuid
from datetime import datetime, timezone

from app.engine.exceptions import BlockError
from app.engine.hashing import hash_record
from app.engine.keys import key_fingerprint, public_key_to_b64
from app.engine.signing import sign_fields, verify_signature

# The first block of a chain points to this "previous hash" (64 zeros).
GENESIS_PREV_HASH = "0" * 64

# Event types from the team doc.
GENESIS = "GENESIS"
REGISTER = "REGISTER"
TRANSFER = "TRANSFER"
ACCEPT = "ACCEPT"

# Events that a user signs (GENESIS is created by the system, unsigned).
SIGNED_EVENTS = (REGISTER, TRANSFER, ACCEPT)

# Exactly which payload fields each event type must have.
PAYLOAD_FIELDS = {
    GENESIS: {"note"},
    REGISTER: {"evidence_sha256", "size_bytes", "mime_type", "original_filename"},
    TRANSFER: {"transfer_id", "from_user_id", "to_user_id", "evidence_sha256", "reason"},
    ACCEPT: {"transfer_id", "evidence_sha256"},
}

# Every field except signature and block_hash.
SIGNING_FIELDS = (
    "index",
    "block_id",
    "timestamp",
    "case_id",
    "evidence_id",
    "event_type",
    "actor_id",
    "key_fingerprint",
    "payload",
    "prev_hash",
)

# The complete list of fields a stored block has.
BLOCK_FIELDS = SIGNING_FIELDS + ("signature", "block_hash")

# Limits from the team doc's input validation table.
MAX_REASON_LENGTH = 1000
MAX_FILENAME_LENGTH = 255

_SHA256_PATTERN = re.compile(r"^[0-9a-f]{64}$")


# ---------- small helpers ----------

def utc_now_iso() -> str:
    """Current UTC time in the team doc's format, e.g. 2026-11-10T08:30:00.123Z."""

    # Take the current time in UTC (never local time, so all laptops agree).
    now = datetime.now(timezone.utc)

    # Format with milliseconds and a trailing Z, as agreed in the team doc.
    return now.strftime("%Y-%m-%dT%H:%M:%S.") + f"{now.microsecond // 1000:03d}Z"


def new_id() -> str:
    """A new random UUIDv4 string (all IDs are generated by the server)."""
    return str(uuid.uuid4())


def is_sha256_hex(value) -> bool:
    """True if value looks like a SHA-256 hash: 64 lowercase hex characters."""
    return isinstance(value, str) and bool(_SHA256_PATTERN.match(value))


# ---------- hashing a block ----------

def signing_fields(block: dict) -> dict:
    """The part of a block that gets signed (everything except signature and hash)."""

    # Pick out the signing fields only. .get() means a missing field becomes
    # None instead of crashing, so a broken block still produces a hash
    # (which will simply not match).
    return {name: block.get(name) for name in SIGNING_FIELDS}


def compute_block_hash(block: dict) -> str:
    """SHA-256 of canonical(signing fields + signature), as the team doc defines."""

    # Start from the signing fields and add the signature on top.
    data = signing_fields(block)
    data["signature"] = block.get("signature")

    # Hash the canonical JSON of the result.
    return hash_record(data)


# ---------- validating a payload ----------

def validate_payload(event_type: str, payload: dict) -> None:
    """Check that a payload has exactly the right fields for its event type."""

    # The event type must be one we know about.
    if event_type not in PAYLOAD_FIELDS:
        raise BlockError("VALIDATION_ERROR", "Unknown event type")

    # The payload must be a dict.
    if not isinstance(payload, dict):
        raise BlockError("VALIDATION_ERROR", "Payload must be an object")

    # Compare the payload's fields with the expected ones: nothing missing,
    # nothing extra (extra fields could hide data inside a signed block).
    expected = PAYLOAD_FIELDS[event_type]
    missing = expected - set(payload)
    extra = set(payload) - expected
    if missing or extra:
        raise BlockError(
            "VALIDATION_ERROR",
            f"{event_type} payload must have exactly these fields: {', '.join(sorted(expected))}",
        )

    # Any evidence hash must be a proper SHA-256 hex string.
    if "evidence_sha256" in payload and not is_sha256_hex(payload["evidence_sha256"]):
        raise BlockError("VALIDATION_ERROR", "evidence_sha256 must be 64 lowercase hex characters")

    # REGISTER: file size must be a positive whole number (empty files are rejected).
    if event_type == REGISTER:
        size = payload["size_bytes"]
        if not isinstance(size, int) or isinstance(size, bool) or size < 1:
            raise BlockError("VALIDATION_ERROR", "size_bytes must be a positive integer")
        if not _is_text(payload["mime_type"], 255):
            raise BlockError("VALIDATION_ERROR", "mime_type must be text")
        if not _is_text(payload["original_filename"], MAX_FILENAME_LENGTH):
            raise BlockError("VALIDATION_ERROR", "original_filename must be 1-255 characters")

    # TRANSFER: IDs must be present and the reason must fit the limit.
    if event_type == TRANSFER:
        for name in ("transfer_id", "from_user_id", "to_user_id"):
            if not _is_text(payload[name], 64):
                raise BlockError("VALIDATION_ERROR", f"{name} must be a non-empty ID")
        reason = payload["reason"]
        if not isinstance(reason, str) or len(reason) > MAX_REASON_LENGTH:
            raise BlockError("VALIDATION_ERROR", "reason must be text of at most 1000 characters")

    # ACCEPT: the transfer being accepted must be named.
    if event_type == ACCEPT and not _is_text(payload["transfer_id"], 64):
        raise BlockError("VALIDATION_ERROR", "transfer_id must be a non-empty ID")


# ---------- building blocks ----------

def create_genesis_block(timestamp: str = None, block_id: str = None) -> dict:
    """The first block of the chain: index 0, created by the system, unsigned."""

    # Fill in the fixed genesis values (no case, no evidence, no signer).
    block = {
        "index": 0,
        "block_id": block_id or new_id(),
        "timestamp": timestamp or utc_now_iso(),
        "case_id": None,
        "evidence_id": None,
        "event_type": GENESIS,
        "actor_id": None,
        "key_fingerprint": None,
        "payload": {"note": "ChainTrace genesis block"},
        "prev_hash": GENESIS_PREV_HASH,
        "signature": None,
    }

    # Seal the block with its hash.
    block["block_hash"] = compute_block_hash(block)
    return block


def build_block(
    prev_block,
    *,
    event_type: str,
    case_id: str,
    evidence_id: str,
    actor_id: str,
    payload: dict,
    private_key,
    timestamp: str = None,
    block_id: str = None,
) -> dict:
    """Build and sign a new REGISTER, TRANSFER or ACCEPT block.

    prev_block is the current last block of the chain, or None if this block
    starts a new chain. The private key is the signer's, already decrypted.
    The block is NOT stored here: call validate_new_block() and then let the
    backend store it.
    """

    # Only user events are built here; GENESIS has its own function.
    if event_type not in SIGNED_EVENTS:
        raise BlockError("VALIDATION_ERROR", "Only REGISTER, TRANSFER and ACCEPT blocks can be signed")

    # Check the payload before signing anything.
    validate_payload(event_type, payload)

    # The IDs that every user block needs.
    for name, value in (("case_id", case_id), ("evidence_id", evidence_id), ("actor_id", actor_id)):
        if not _is_text(value, 64):
            raise BlockError("VALIDATION_ERROR", f"{name} must be a non-empty ID")

    # Link to the previous block (or to 64 zeros if this starts a chain).
    if prev_block is None:
        index = 0
        prev_hash = GENESIS_PREV_HASH
    else:
        index = prev_block["index"] + 1
        prev_hash = prev_block["block_hash"]

    # Work out the signer's key fingerprint from their private key.
    public_b64 = public_key_to_b64(private_key.public_key())

    # Put the block together (copy the payload so later changes can't leak in).
    block = {
        "index": index,
        "block_id": block_id or new_id(),
        "timestamp": timestamp or utc_now_iso(),
        "case_id": case_id,
        "evidence_id": evidence_id,
        "event_type": event_type,
        "actor_id": actor_id,
        "key_fingerprint": key_fingerprint(public_b64),
        "payload": dict(payload),
        "prev_hash": prev_hash,
    }

    # Sign the signing fields, then seal the block with its hash.
    block["signature"] = sign_fields(signing_fields(block), private_key)
    block["block_hash"] = compute_block_hash(block)
    return block


# ---------- checking a block before it is appended ----------

def validate_new_block(last_block, block: dict, signer_public_key_b64: str = None) -> None:
    """Rules 1 and 2 from the team doc, checked right before a block is stored.

    Rule 1: the block must sit exactly on the end of the chain
            (index = last + 1, prev_hash = last block's hash).
    Rule 2: the signature must verify against the signer's STORED public key.

    Raises BlockError if anything is wrong; returns None if the block is fine.
    """

    # The block must have exactly the agreed fields.
    if not isinstance(block, dict) or set(block) != set(BLOCK_FIELDS):
        raise BlockError("VALIDATION_ERROR", "Block fields are missing or unexpected")

    # The payload must match its event type.
    validate_payload(block["event_type"], block["payload"])

    # Rule 1: the block must extend the current end of the chain.
    expected_index = 0 if last_block is None else last_block["index"] + 1
    expected_prev = GENESIS_PREV_HASH if last_block is None else last_block["block_hash"]
    if block["index"] != expected_index or block["prev_hash"] != expected_prev:
        raise BlockError("CHAIN_CONFLICT", "Block does not extend the current end of the chain")

    # The stored hash must match the block's contents.
    if block["block_hash"] != compute_block_hash(block):
        raise BlockError("BLOCK_HASH_INVALID", "Block hash does not match its contents")

    # GENESIS: only allowed as the unsigned first block.
    if block["event_type"] == GENESIS:
        if last_block is not None or block["signature"] is not None or block["actor_id"] is not None:
            raise BlockError("VALIDATION_ERROR", "GENESIS is only allowed as the unsigned first block")
        return

    # Rule 2: the block must be signed by the key registered for this user.
    # First, the fingerprint in the block must match the stored public key.
    try:
        registered_fingerprint = key_fingerprint(signer_public_key_b64)
    except ValueError:
        raise BlockError("INVALID_SIGNATURE", "Signature check failed for this block") from None
    if block["key_fingerprint"] != registered_fingerprint:
        raise BlockError("INVALID_SIGNATURE", "Signature check failed for this block")

    # Then the signature itself must verify over the signing fields.
    if not verify_signature(signing_fields(block), block["signature"], signer_public_key_b64):
        raise BlockError("INVALID_SIGNATURE", "Signature check failed for this block")


# ---------- private helpers ----------

def _is_text(value, max_length: int) -> bool:
    """True if value is a non-empty string no longer than max_length."""
    return isinstance(value, str) and 0 < len(value) <= max_length
