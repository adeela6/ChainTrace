"""Run the test suite and write docs/test-results.md from the results.

Usage (from the repo root, venv active):
    python scripts/make_test_results.py              # run pytest, then write the table
    python scripts/make_test_results.py -m "not slow"  # extra args go to pytest
    python scripts/make_test_results.py --from build/junit.xml   # reuse an earlier run

Evaluation tests (T1-T6, T-final) become rows in the agreed results table.
Mark them like this so they show up:

    @pytest.mark.evaluation_case(id="T1", input="block 5 payload edited",
                                 expected="FAIL at BLOCK_HASH_VALID, block 5")

Exits with pytest's exit code, so CI still fails when tests fail.
"""

import argparse
import platform
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JUNIT_PATH = ROOT / "build" / "junit.xml"
OUTPUT_PATH = ROOT / "docs" / "test-results.md"

# Every evaluation test the team agreed on, in report order.
PLANNED = {
    "T1": ("Tampered record: block 5 payload edited", "FAIL at BLOCK_HASH_VALID, block 5"),
    "T2": ("Altered file: one byte of an evidence file changed", "FAIL at FILE_HASH_MATCH for that evidence"),
    "T3": ("Invalid signature: wrong key; flipped signature byte", "422 INVALID_SIGNATURE; FAIL at SIGNATURE_VALID"),
    "T4": ("Duplicate transfer; transfer by non-custodian", "409 DUPLICATE_TRANSFER / NOT_CUSTODIAN, nothing appended"),
    "T5": ("Clean 50+ block chain; then a middle block deleted", "PASS on clean; FAIL at PREV_HASH_LINK"),
    "T5b": ("Newest blocks deleted after a verification recorded the head",
            "FAIL at CHAIN_HEAD_CONSISTENT"),
    "T6": ("Viewer views case; report and audit exported", "No secrets anywhere; viewer sees redacted fields"),
    "T-final": ("Malformed JSON, 30 MB file, fake .png, wrong role, repeat submit, restart",
                "Correct error codes, no stack traces, data intact, chain PASS"),
}

PASS_TARGET = 0.80


def run_pytest(extra_args: list[str]) -> int:
    JUNIT_PATH.parent.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, "-m", "pytest", f"--junitxml={JUNIT_PATH}", *extra_args]
    print("Running:", " ".join(command))
    return subprocess.call(command, cwd=ROOT)


def parse_junit(path: Path) -> list[dict]:
    results = []
    for case in ET.parse(path).getroot().iter("testcase"):
        props = {p.get("name"): p.get("value") for p in case.iter("property")}
        outcome, detail = "passed", ""
        for tag in ("failure", "error", "skipped"):
            node = case.find(tag)
            if node is not None:
                outcome = {"failure": "failed", "error": "error", "skipped": "skipped"}[tag]
                detail = node.get("message") or (node.text or "")
                break
        file = case.get("file") or case.get("classname", "").replace(".", "/") + ".py"
        results.append({
            "nodeid": f"{file.replace(chr(92), '/')}::{case.get('name')}",
            "outcome": outcome,
            "detail": detail,
            "eval_id": props.get("eval_id"),
            "eval_input": props.get("eval_input"),
            "eval_expected": props.get("eval_expected"),
        })
    return results


def cell(text: str, limit: int = 160) -> str:
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def area(nodeid: str) -> str:
    parts = nodeid.split("/")
    return parts[1] if len(parts) > 2 and parts[0] == "tests" else "other"


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render(results: list[dict]) -> str:
    counts = Counter(r["outcome"] for r in results)
    ran = counts["passed"] + counts["failed"] + counts["error"]
    pass_rate = counts["passed"] / ran if ran else 0.0
    verdict = "meets" if pass_rate >= PASS_TARGET else "below"
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# Test Results",
        "",
        "Generated by `python scripts/make_test_results.py`. Don't edit by hand; rerun the script.",
        "",
        f"Run: {now} · commit `{git_commit()}` · Python {platform.python_version()} · {platform.system()}",
        "",
        "## Summary",
        "",
        "| Total | Passed | Failed | Errors | Skipped | Pass rate |",
        "|---|---|---|---|---|---|",
        (
            f"| {len(results)} | {counts['passed']} | {counts['failed']} | {counts['error']} | {counts['skipped']} "
            f"| {pass_rate:.0%} ({verdict} the {PASS_TARGET:.0%} target) |"
        ),
        "",
        "Pass rate = passed ÷ (passed + failed + errors). Skipped tests are listed below with their reason.",
        "",
        "## Evaluation tests",
        "",
        "| ID | Input | Expected | Actual | Evidence | Pass/Fail |",
        "|---|---|---|---|---|---|",
    ]

    by_id = defaultdict(list)
    for r in results:
        if r["eval_id"]:
            by_id[r["eval_id"]].append(r)

    for test_id in [*PLANNED, *sorted(set(by_id) - set(PLANNED))]:
        planned_input, planned_expected = PLANNED.get(test_id, ("", ""))
        rows = by_id.get(test_id)
        if not rows:
            lines.append(f"| {test_id} | {cell(planned_input)} | {cell(planned_expected)} | not written yet | | NOT RUN |")
            continue
        for r in rows:
            status = {"passed": "PASS", "failed": "FAIL", "error": "ERROR", "skipped": "SKIPPED"}[r["outcome"]]
            actual = "as expected" if r["outcome"] == "passed" else cell(r["detail"] or r["outcome"])
            lines.append(
                f"| {test_id} | {cell(r['eval_input'])} | {cell(r['eval_expected'])} | {actual} "
                f"| `{cell(r['nodeid'], 200)}` | {status} |"
            )

    lines += ["", "## All tests by area", "", "| Area | Passed | Failed | Errors | Skipped |", "|---|---|---|---|---|"]
    by_area = defaultdict(Counter)
    for r in results:
        by_area[area(r["nodeid"])][r["outcome"]] += 1
    for name in sorted(by_area):
        c = by_area[name]
        lines.append(f"| {name} | {c['passed']} | {c['failed']} | {c['error']} | {c['skipped']} |")

    problems = [r for r in results if r["outcome"] in {"failed", "error"}]
    if problems:
        lines += ["", "## Failures", "", "| Test | Message |", "|---|---|"]
        lines += [f"| `{cell(r['nodeid'], 200)}` | {cell(r['detail'])} |" for r in problems]

    skipped = [r for r in results if r["outcome"] == "skipped"]
    if skipped:
        lines += ["", "## Skipped", "", "| Test | Reason |", "|---|---|"]
        lines += [f"| `{cell(r['nodeid'], 200)}` | {cell(r['detail'])} |" for r in skipped]

    lines += [
        "",
        "## Manual checks",
        "",
        "Accessibility and on-screen checks from section 9 of the test plan. Fill in with screenshot links.",
        "",
        "| Check | Result | Evidence |",
        "|---|---|---|",
        "| Every input has a label | not checked yet | |",
        "| Every action works by keyboard only | not checked yet | |",
        "| Text contrast at least 4.5:1 | not checked yet | |",
        "| `<script>` in titles and reasons shows as text | not checked yet | |",
        "| Confirmation dialogs before transfer, accept and config changes | not checked yet | |",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--from", dest="junit", type=Path, help="use an existing JUnit XML file instead of running pytest")
    args, pytest_args = parser.parse_known_args()

    exit_code = 0
    junit = args.junit
    if junit is None:
        exit_code = run_pytest(pytest_args)
        junit = JUNIT_PATH
    if not junit.exists():
        print(f"No results file at {junit}", file=sys.stderr)
        return exit_code or 1

    OUTPUT_PATH.write_text(render(parse_junit(junit)), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT)}")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
